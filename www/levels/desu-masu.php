  <h1>Wprowadzenie do desu/masu</h1>
  <div class="article-meta-desu">
    <span>Gramatyka</span><span class="dot"></span><span>3 min czytania</span>
  </div>

  <div class="article-body">
    <p>
      Język japoński ma różne poziomy grzeczności. Podstawowy i najczęściej spotykany w codziennych rozmowach jest
      tzw. styl <strong>desu/masu</strong>, używany w sytuacjach oficjalnych, z nieznajomymi lub gdy chcemy okazać szacunek.
    </p>
    <p>
      Kopula <strong>です (desu)</strong> pełni funkcję „być” w znaczeniu identyfikacji. 
      Na przykład: <em>Watashi wa gakusei desu</em> (私は学生です) – „Jestem studentem”.
    </p>
    <p>
      Czasowniki w stylu uprzejmym przybierają końcówkę <strong>-ます</strong>. 
      Na przykład: <em>tabemasu</em> (食べます) – „jem”, <em>mimasu</em> (見ます) – „oglądam”.
    </p>
    <p>
      Styl ten kontrastuje z formą prostą, używaną wśród przyjaciół lub w literaturze. 
      Różnica między „tabemasu” i „taberu” jest kluczowa dla rozumienia sytuacji komunikacyjnej.
    </p>
    <p>
      Opanowanie desu/masu to pierwszy krok do płynnej komunikacji po japońsku – daje możliwość grzecznego, a zarazem naturalnego wyrażania się.
    </p>
  </div>

